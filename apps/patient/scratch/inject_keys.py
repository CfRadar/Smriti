with open(r'd:\SIH2026\Smriti\apps\patient\lib\l10n\app_translations.dart', 'r', encoding='utf-8') as f:
    content = f.read()

# For each language, inject the new keys before the closing '    },' of that language map
for lang in ['en', 'hi', 'as', 'bn', 'lus', 'mni']:
    lang_header = f"'{lang}': {{"
    lang_idx = content.find(lang_header)
    if lang_idx == -1:
        print(f"Error: {lang_header} not found!")
        continue
    
    # Find the closing '    },' for this language
    # Next lang header or end of strings map
    next_langs = [l for l in ['hi', 'as', 'bn', 'lus', 'mni'] if l != lang]
    end_idx = len(content)
    for nl in next_langs:
        p = content.find(f"'{nl}': {{", lang_idx + 10)
        if p != -1 and p < end_idx:
            end_idx = p
    
    closing_pattern = "\n    },"
    close_pos = content.rfind(closing_pattern, lang_idx, end_idx)
    if close_pos == -1:
        # Maybe last lang 'mni' ends with "\n    }," or "\n    }\n  };"
        closing_pattern = "\n    }\n  };"
        close_pos = content.rfind(closing_pattern, lang_idx, end_idx)
        if close_pos == -1:
            close_pos = content.find("\n    }", lang_idx)
    
    lines_to_add = []
    lines_to_add.append("\n      // Extended Activities, Folklore & Karaoke Keys")
    for k, v in NEW_KEYS[lang].items():
        val_escaped = v.replace("'", "\\'")
        lines_to_add.append(f"      '{k}': '{val_escaped}',")
    
    addition = "\n".join(lines_to_add)
    content = content[:close_pos] + addition + content[close_pos:]
    print(f"Injected {len(NEW_KEYS[lang])} keys into '{lang}'")

with open(r'd:\SIH2026\Smriti\apps\patient\lib\l10n\app_translations.dart', 'w', encoding='utf-8') as f:
    f.write(content)

print("Successfully updated app_translations.dart!")
